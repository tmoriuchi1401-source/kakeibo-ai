CATEGORIES=[('食費','食品')]

def setup(kinds=('medical','normal')):
    g,live,transport=context(kinds)
    view=g.display('drive-source-id')
    human=PageKindConfirmation(g)
    human.confirm(view['proposal'],{1:'医療',2:'一般'})
    view=g.regenerate_general('drive-source-id',lambda *_:{2:PageEvidence()})
    g.review(request(view))
    value=g.store.load();record=value['records'][_digest('drive-source-id')];p=record['proposal']
    unit=g.confirmed_units('drive-source-id')[0]
    expected={k:p[k] for k in ('source_file_id','source_content_hash','page_count','proposal_digest')}
    expected.update(binding=g.store.binding,grouping_revision=record['revision'],confirmation_digest=record['confirmation']['confirmation_digest'],unit_ids={2:unit.unit_id})
    content=synthetic_pdf(kinds)
    # PDF attachment/content is deterministically generated by the fixture.
    assert sha256(content).hexdigest()==p['source_content_hash']
    result=ReceiptResult(date='2026-09-01',merchant='テスト店',total=100,payment_method='現金',
                         items=[dict(name='商品',amount=100,major_category='食費',minor_category='食品')])
    analyze=Mock(return_value=(result,[result]))
    service=ro.ReadonlyPdfReceipts(g.store.load,Mock(return_value=content),analyze,CATEGORIES,expected,model='synthetic')
    return service,g,transport,analyze,value

def test_confirmed_single_rgb_page_only_and_replay_never_write(local_ocr):
    svc,g,t,ai,_=setup();before=t.payload;writes=t.writes;local_ocr.clear()
    first=svc.run(2);second=svc.run(2)
    assert first['status']==second['status']=='would_import'
    assert first['unit_id']==second['unit_id']
    assert svc.budget.peak_live_pages==1 and svc.budget.live_pages==0
    assert set(local_ocr)=={'normal'}  # p1 not rendered or observed
    png=ai.call_args.args[0]
    with Image.open(BytesIO(png)) as image:
        assert image.mode=='RGB' and image.info=={} and kind_of(image)=='normal'
    assert b'%PDF-' not in png and b'PRIVATE_ATTACHMENT_99' not in png
    assert t.payload==before and t.writes==writes
    assert first['accounting_allowed'] is first['medical_handoff_allowed'] is first['archive_allowed'] is False

@pytest.mark.parametrize('change',['unconfirmed','medical','hash','revision','digest','unit','page_hash'])
def test_stale_or_unconfirmed_never_send(local_ocr,change):
    svc,g,t,ai,value=setup();record=value['records'][_digest('drive-source-id')]
    if change=='unconfirmed':record['confirmation']=None;record['status']='held'
    elif change=='medical':svc.expected['unit_ids'][1]='fake'
    elif change=='hash':svc.load_source=Mock(return_value=b'%PDF-changed')
    elif change=='revision':svc.expected['grouping_revision']+=1
    elif change=='digest':svc.expected['confirmation_digest']='0'*64
    elif change=='unit':svc.expected['unit_ids'][2]='fake'
    elif change=='page_hash':
        svc.load_source=Mock(return_value=synthetic_pdf(('medical','payroll')))
        # Deliberately inconsistent fresh raster/source proof fails before send.
        svc.expected['source_content_hash']=sha256(svc.load_source()).hexdigest()
        record['proposal']['source_content_hash']=svc.expected['source_content_hash']
    svc.load_authority=Mock(return_value=value)
    outcome=svc.run(1 if change=='medical' else 2)
    assert outcome['status']=='authority_held';ai.assert_not_called()

