@pytest.mark.parametrize('failure',['render','page_hash','exact_gate','ocr','adapter_gate'])
def test_payload_failure_never_calls_gemini(local_ocr,monkeypatch,failure):
    svc,g,t,ai,_=setup()
    if failure=='render':monkeypatch.setattr(ro,'_render_png',Mock(side_effect=ro.RenderHold('render_failed')))
    if failure=='page_hash':monkeypatch.setattr(ro,'_render_png',Mock(return_value=b'different raster'))
    if failure=='exact_gate':
        gate,_=ro._checked_gate(g.load_observations('drive-source-id',None).pages[1]._payload,'normal')
        monkeypatch.setattr(ro,'_checked_gate',Mock(return_value=(gate,False)))
    if failure=='ocr':monkeypatch.setattr(ro,'_extract_receipt_text',Mock(side_effect=ValueError('PRIVATE RAW')))
    if failure=='adapter_gate':ai.side_effect=ro.ReceiptPrivacyBlocked()
    report=svc.run(2)
    if failure!='adapter_gate':ai.assert_not_called()
    assert report['status'] in {'authority_held','privacy_blocked','analysis_failed'}
    assert 'PRIVATE RAW' not in str(report)

